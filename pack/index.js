import data from './book.json';

/**
 * The Raven, as a pack.
 *
 * `book.json` is the poem: the stanzas, the glossary, the questions, the
 * two of them talking about each part. It is generated from
 * `build/the-raven.html` and there is nothing in it about files.
 *
 * This file is the rest of the pack — where the art and the recordings
 * sit once `tools/extract-media.mjs` has run.
 *
 * WHY THE PICTURE PATHS ARE HERE AND NOT IN book.json
 *
 * Magi keeps its plate map in its book.json, and that is right for Magi:
 * its art is content-addressed, so `art/3ded1a00f03753bd.webp` cannot be
 * derived from the scene id. Lose that map and there is no way back from
 * a scene to its picture. The map carries information, so it is data.
 *
 * The Raven's art is not content-addressed. Every file is named for the
 * key the build used, so `s9` -> `art/plate-s9.webp` is not a fact about
 * the poem, it is the naming scheme one tool chose. That makes it
 * deployment, and deployment belongs in the pack, next to the audio
 * paths, in the file a person edits when the layout changes.
 *
 * The other half of the reason is mechanical. `book/book.json` is
 * generated by the engine's extractor, and this repository already has a
 * scar from editing generated output: `tools/fix-glossary.mjs` exists
 * because a hand-typed correction was silently undone by the next
 * extraction. Paths written into a generated file would go the same way.
 *
 * Relative, with no leading slash — see MEDIA_BASE in reader/beats.js.
 * itch serves a game from a nested path, so "/art/plate-s9.webp"
 * resolves against the domain root and 404s for every picture.
 */

